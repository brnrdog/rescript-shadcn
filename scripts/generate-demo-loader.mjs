#!/usr/bin/env node
// Generates the lib-aware demo loader from every registry example tree.
// Usage: node scripts/generate-demo-loader.mjs

import { readdirSync, writeFileSync } from "fs";
import { basename } from "path";

const OUTPUT_FILE = "src/generated/DemoLoader.res";

// Files to exclude (they're used for sources, not for demos)
const EXCLUDE = new Set(["DataTableColumnHeader", "DataTablePagination", "DataTableViewOptions"]);

const getNames = (lib) =>
  readdirSync(`registry/${lib}/examples`)
    .filter((f) => f.endsWith(".res") && !f.startsWith("."))
    .map((f) => basename(f, ".res"))
    .filter((name) => !EXCLUDE.has(name))
    .sort();

const makeEntries = (names, packageName) => names
  .map(
    (name) =>
      `  "${name}": module({
      let load: unit => promise<React.component<RescriptShadcn.Demo.Props.t>> = %raw(\`() => import("${packageName}/examples/${name}.res.mjs").then(m => m.make)\`)
      let make = React.lazy_(load)
    }: RescriptShadcn.Demo.Component),`
  )
  .join("\n");

// xote demos build DOM nodes instead of React elements, so they are loaded as
// plain functions and mounted by XoteDemo.
const makeXoteEntries = (names, packageName) => names
  .map(
    (name) =>
      `  "${name}": %raw(\`() => import("${packageName}/examples/${name}.res.mjs").then(m => m.make)\`),`
  )
  .join("\n");

const baseNames = getNames("base");
const ariaNames = getNames("aria");
const xoteNames = getNames("xote");

const output = `// @generated by scripts/generate-demo-loader.mjs — do not edit manually.
@@directive("'use client'")

let baseDemos = dict{
${makeEntries(baseNames, "rescript-shadcn-base")}
};

let ariaDemos = dict{
${makeEntries(ariaNames, "rescript-shadcn-aria")}
};

let xoteDemos: dict<XoteDemo.loader> = dict{
${makeXoteEntries(xoteNames, "rescript-shadcn-xote")}
};

@react.component
let make = (~name: string, ~lib: option<Config.Lib.t>=?) => {
  let (libStyle, _, _) = Config.LibStyle.use()
  let activeLib = lib->Option.getOr(libStyle.Config.LibStyle.lib)
  switch activeLib {
  | Config.Lib.Xote =>
    switch xoteDemos->Dict.get(name) {
    | None => React.null
    | Some(load) => <XoteDemo load />
    }
  | Config.Lib.Base | Config.Lib.Aria =>
    let demos = switch activeLib {
    | Config.Lib.Aria => ariaDemos
    | _ => baseDemos
    }
    switch demos->Dict.get(name) {
    | None => React.null
    | Some(module(Comp)) =>
      <React.Suspense fallback={<Skeleton />}>
        <Comp />
      </React.Suspense>
    }
  }
}
`;

writeFileSync(OUTPUT_FILE, output);
console.log(
  `Generated ${OUTPUT_FILE} with ${baseNames.length} base, ${ariaNames.length} aria and ${xoteNames.length} xote demos (excluded: ${[...EXCLUDE].join(", ")})`
);
