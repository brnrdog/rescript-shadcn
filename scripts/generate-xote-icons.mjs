#!/usr/bin/env node
// Generates registry/xote/ui/Icons.res from lucide-static.
//
// The React registries import lucide-react; the xote components inline the same
// artwork as SVG instead, so a copied component pulls in no icon dependency.
// The icon set is whatever the base registry's components and examples use.
//
// Usage: node scripts/generate-xote-icons.mjs

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import path from "node:path"

const packageRoot = new URL("..", import.meta.url).pathname
const iconsDir = path.join(packageRoot, "node_modules", "lucide-static", "icons")
const outputFile = path.join(packageRoot, "registry", "xote", "ui", "Icons.res")

/** lucide renamed a batch of icons; the base registry still uses the old names. */
const ALIASES = {
  AlertTriangle: "triangle-alert",
  AlertCircle: "circle-alert",
  CheckCircle: "circle-check",
  CheckCircle2: "circle-check-big",
  HelpCircle: "circle-help",
  XCircle: "circle-x",
  PlusCircle: "circle-plus",
  MinusCircle: "circle-minus",
  MoreHorizontal: "ellipsis",
  MoreVertical: "ellipsis-vertical",
  Loader2: "loader-circle",
  Loader: "loader-circle",
  Trash: "trash",
  Edit: "pencil",
  Edit2: "pencil",
  Edit3: "pencil-line",
  Settings2: "settings-2",
  Layout: "layout-panel-left",
  Image: "image",
  Radio: "radio",
  Dot: "dot",
  Building2: "building-2",
  Clock2: "clock-2",
  Link2: "link-2",
  Trash2: "trash-2",
}

const kebab = (name) =>
  name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
    .toLowerCase()

function iconFile(name) {
  const candidates = [ALIASES[name], kebab(name)].filter(Boolean)
  for (const candidate of candidates) {
    const file = path.join(iconsDir, `${candidate}.svg`)
    if (existsSync(file)) return file
  }
  return null
}

/** The shapes inside the <svg>, with attributes normalised to JSX prop names. */
function extractShapes(file) {
  const svg = readFileSync(file, "utf8")
  const body = svg.slice(svg.indexOf(">") + 1, svg.lastIndexOf("</svg>"))
  const shapes = body.match(/<(path|circle|rect|line|polyline|polygon|ellipse)\b[^>]*\/>/g)
  if (!shapes) return null

  return shapes.map((shape) => {
    const tag = shape.match(/^<(\w+)/)[1]
    const attrs = [...shape.matchAll(/([\w:-]+)="([^"]*)"/g)].map(([, key, value]) => {
      const prop = key.replace(/-([a-z])/g, (_, char) => char.toUpperCase())
      return `${prop}="${value}"`
    })
    return `      <${tag} ${attrs.join(" ")} />`
  })
}

/** Icon names referenced anywhere in the base registry. */
function usedIcons() {
  const names = new Set()
  for (const dir of ["ui", "examples"]) {
    const base = path.join(packageRoot, "registry", "base", dir)
    for (const file of readdirSync(base)) {
      if (!file.endsWith(".res")) continue
      const source = readFileSync(path.join(base, file), "utf8")
      for (const [, name] of source.matchAll(/\bIcons\.([A-Z]\w+)/g)) names.add(name)
    }
  }
  // Used by the xote components themselves.
  for (const name of ["Check", "ChevronDown", "ChevronUp", "ChevronRight", "ChevronLeft", "X", "ArrowUp", "Minus", "Search", "Plus", "MoreHorizontal"]) {
    names.add(name)
  }
  return [...names].sort()
}

const header = `// @generated by scripts/generate-xote-icons.mjs — do not edit manually.

/* Inline icons, so a copied component needs no icon dependency. The artwork is
   lucide, the same set the React registries pull from lucide-react. */

module Svg = {
  @xote.component
  let make = (
    ~className: option<string>=?,
    ~dataSlot: option<string>=?,
    ~dataIcon: option<string>=?,
    ~ariaLabel: option<string>=?,
    ~role: option<string>=?,
    ~children: View.node,
  ) =>
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      class=?{className}
      role=?{role}
      ariaLabel=?{ariaLabel}
      attrs=[View.optionalAttr("data-slot", dataSlot), View.optionalAttr("data-icon", dataIcon)]>
      {children}
    </svg>
}
`

const modules = []
const skipped = []

for (const name of usedIcons()) {
  const file = iconFile(name)
  const shapes = file && extractShapes(file)
  if (!shapes) {
    skipped.push(name)
    continue
  }

  modules.push(`
module ${name} = {
  @xote.component
  let make = (
    ~className: option<string>=?,
    ~dataSlot: option<string>=?,
    ~dataIcon: option<string>=?,
    ~ariaLabel: option<string>=?,
    ~role: option<string>=?,
  ) =>
    <Svg ?className ?dataSlot ?dataIcon ?ariaLabel ?role>
${shapes.join("\n")}
    </Svg>
}`)
}

writeFileSync(outputFile, header + modules.join("\n") + "\n")
console.log(
  `Wrote ${path.relative(packageRoot, outputFile)} with ${modules.length} icons` +
    (skipped.length ? ` (no lucide match: ${skipped.join(", ")})` : "")
)
